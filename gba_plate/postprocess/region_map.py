# --------------------------------------------------------------------- 查詢

@lru_cache(maxsize=512)
def resolve_plate_region(text: str) -> tuple[str | None, str | None, str]:
    """
    解析車牌的省份與地級市。

    Args:
        text: 正規化的車牌文字（如 "粤B12345"）

    Returns:
        (省全名, 地級市, 補充說明)。非內地車牌回傳 (None, None, 原因)

    Examples:
        >>> resolve_plate_region("粤B12345")
        ('廣東省', '深圳市', '')
        >>> resolve_plate_region("粤Z1234港")
        ('廣東省', '港澳入出內地車輛', '香港入出')
        >>> resolve_plate_region("京A12345")
        ('北京市', '北京市區', '')
    """
    if not text or len(text) < 2:
        return None, None, "車牌過短"

    province_char = text[0]
    province = PROVINCE_NAMES.get(province_char)
    if province is None:
        return None, None, f"'{province_char}' 不是省級簡稱"

    # 第 2 位必須是字母（發牌機關代碼）
    code = text[1]
    if not code.isalpha():
        return None, None, f"第 2 位 '{code}' 不是字母"

    # 粵Z 特殊處理：Z 代表港澳入出內地車輛
    if province_char == "粤" and code == "Z":
        suffix = text[-1] if text else ""
        note = GANGAO_SUFFIX_NOTE.get(suffix, "")
        return province, "港澳入出內地車輛", note

    cities = CITY_CODES.get(province_char)
    if not cities:
        return province, None, "該省份暫無地級市對照"

    city = cities.get(code)
    if city is None:
        # 字母不存在於該省（如粵I/粵O 不存在）
        return province, None, f"'{province_char}{code}' 非民用車牌代碼"

    return province, city, ""


def format_plate_region(text: str) -> str:
    """
    格式化為可讀字串（給 UI / log 用）。

    Examples:
        >>> format_plate_region("粤B12345")
        '廣東省 · 深圳市'
        >>> format_plate_region("粤Z1234港")
        '廣東省 · 港澳入出內地車輛（香港入出）'
        >>> format_plate_region("AB1234")
        ''
    """
    province, city, note = resolve_plate_region(text)
    if province is None:
        return ""

    parts = [province]
    if city:
        parts.append(city)

    result = " · ".join(parts)
    if note:
        result += f"（{note}）"
    return result


# ------------------------------------------------------------------ 能源類型

def resolve_energy(text: str) -> tuple[str | None, str]:
    """
    解析新能源車牌的能源類型。

    規則（92 式新能源號牌，8 位）：
        小型車：能源字母在**第 3 位**（省 + 發牌機關 + 能源 + 5 位）
        大型車：能源字母在**末位**（省 + 發牌機關 + 5 位 + 能源）

    D/A/B/C/E/P/Q/R/S/T → 純電動
    F/G/H/J/K/L/M/N     → 非純電動（插電混動、燃料電池）

    普通車牌（7 位）沒有能源標識，回傳 (None, "")。

    Args:
        text: 正規化車牌文字

    Returns:
        (能源代碼, 說明)。非新能源車回傳 (None, "")

    Examples:
        >>> resolve_energy("沪AF71017")
        ('F', '非純電動（混動/燃料電池）')
        >>> resolve_energy("京AD12345")
        ('D', '純電動')
        >>> resolve_energy("京A12345")
        (None, '')
    """
    if not text:
        return None, ""

    # 只處理純 8 位英數新能源牌；帶中文後綴（警/学/领…）的不是新能源
    if len(text) != 8:
        return None, ""

    # 末位若為中文（警/学/领/使），不是新能源牌
    if not text[-1].isalnum():
        return None, ""

    # 小型新能源：第 3 位（index 2）
    third = text[2]
    if third in ENERGY_LABELS:
        return third, ENERGY_LABELS[third]

    # 大型新能源：末位
    last = text[-1]
    if last in ENERGY_LABELS and last != third:
        return last, ENERGY_LABELS[last] + "（大型車）"

    return None, ""


def describe_plate(text: str) -> str:
    """
    完整描述：省 · 市 · 能源。

    Examples:
        >>> describe_plate("粤B12345")
        '廣東省 · 深圳市'
        >>> describe_plate("沪AF71017")
        '上海市 · 上海市區 · 非純電動（混動/燃料電池）'
        >>> describe_plate("粤Z1234港")
        '廣東省 · 港澳入出內地車輛（香港入出）'
    """
    loc = format_plate_region(text)
    _, energy_note = resolve_energy(text)

    if not loc:
        return energy_note
    if not energy_note:
        return loc
    return f"{loc} · {energy_note}"


